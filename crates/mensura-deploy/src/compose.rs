//! The compose target (ADR 0046 decision 3): a complete, includable
//! compose project with one service per instance, the runtime
//! configurations it mounts, and the scripts that bring it up and down.
//!
//! Every file is rendered as text rather than serialized, so that the
//! bundle reads as a person would write it and diffs cleanly in review.
//! Every string value is emitted double-quoted with JSON escaping, which
//! is valid in both YAML and TOML.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::config::{DeployConfig, Instance};
use crate::{CONFIG_DIR, CONTAINER_PORT, DATA_DIR, DATABASE_ENV};

/// A double-quoted string, valid in YAML and TOML alike.
fn quote(s: &str) -> String {
    serde_json::to_string(s).expect("a string serializes")
}

fn quoted_list<'a>(items: impl IntoIterator<Item = &'a str>) -> String {
    let items: Vec<String> = items.into_iter().map(quote).collect();
    format!("[{}]", items.join(", "))
}

fn header(comment: &str, config_name: &str) -> String {
    format!(
        "{comment} Generated by `mensura deploy` from {config_name}; edit that file\n\
         {comment} and regenerate rather than editing this one.\n"
    )
}

/// The runtime configuration of one instance (ADR 0045 decision 10), as
/// it is mounted at `/etc/mensura/<instance>.toml`.
pub fn runtime_config(
    config: &DeployConfig,
    instance: &Instance,
    program_name: &str,
    config_name: &str,
) -> String {
    let mut out = header("#", config_name);
    let roles = quoted_list(instance.roles.iter().map(|r| r.name()));
    let _ = write!(
        out,
        "\nprogram   = {}\n\
         database  = {{ env = {} }}\n\
         namespace = {}\n\
         roles     = {roles}\n\
         listen    = {}\n\
         \n[limits]\n\
         max_body_bytes    = {}\n\
         min_position_wait = {}\n",
        quote(program_name),
        quote(DATABASE_ENV),
        quote(&config.namespace),
        quote(&format!("0.0.0.0:{CONTAINER_PORT}")),
        config.limits.max_body_bytes,
        quote(&config.limits.min_position_wait),
    );
    for p in &config.principals {
        let _ = write!(
            out,
            "\n[[principal]]\n\
             id           = {}\n\
             token_sha256 = {}\n\
             scopes       = {}\n",
            quote(&p.id),
            quote(&p.token_sha256),
            quoted_list(p.scopes.iter().map(String::as_str)),
        );
    }
    out
}

/// The database address an instance's environment carries.  On SQLite it
/// is a path on the data volume, not a secret, but it goes through the
/// same reference so that the Postgres case changes nothing in `serve`.
pub fn database_address(config: &DeployConfig) -> String {
    format!("sqlite:{DATA_DIR}/{}.db", config.namespace)
}

/// The label that carries the digest of an instance's mounted files.
pub const DIGEST_LABEL: &str = "io.mensura.mounted-sha256";

/// `compose.yaml`: the project, one service per instance, and the named
/// data volume.  `digests` maps each instance to the digest of the files
/// it mounts, written as a label so that compose recreates the instance
/// when they change.
pub fn compose_file(
    config: &DeployConfig,
    config_name: &str,
    digests: &BTreeMap<String, String>,
) -> String {
    let mut out = header("#", config_name);
    let _ = writeln!(out, "\nname: {}\n\nservices:", quote(&config.target.name));
    for instance in &config.instances {
        let config_file = format!("{CONFIG_DIR}/{}.toml", instance.name);
        let health_addr = format!("127.0.0.1:{CONTAINER_PORT}");
        let _ = writeln!(out, "  {}:", instance.name);
        let _ = writeln!(out, "    image: {}", quote(&config.target.image));
        let _ = writeln!(
            out,
            "    command: {}",
            quoted_list(["serve", "--config", config_file.as_str()])
        );
        if let Some(digest) = digests.get(&instance.name) {
            let _ = writeln!(out, "    labels:");
            let _ = writeln!(out, "      {DIGEST_LABEL}: {}", quote(digest));
        }
        let _ = writeln!(out, "    environment:");
        let _ = writeln!(
            out,
            "      {DATABASE_ENV}: {}",
            quote(&database_address(config))
        );
        let _ = writeln!(out, "    volumes:");
        let _ = writeln!(out, "      - type: bind");
        let _ = writeln!(out, "        source: ./mensura");
        let _ = writeln!(out, "        target: {CONFIG_DIR}");
        let _ = writeln!(out, "        read_only: true");
        let _ = writeln!(out, "      - type: volume");
        let _ = writeln!(out, "        source: data");
        let _ = writeln!(out, "        target: {DATA_DIR}");
        let _ = writeln!(out, "    ports:");
        let _ = writeln!(
            out,
            "      - {}",
            quote(&format!("{}:{CONTAINER_PORT}", instance.publish_addr()))
        );
        if let Some(memory) = &instance.memory {
            let _ = writeln!(out, "    deploy:");
            let _ = writeln!(out, "      resources:");
            let _ = writeln!(out, "        limits:");
            let _ = writeln!(out, "          memory: {}", quote(memory));
        }
        let _ = writeln!(out, "    restart: unless-stopped");
        let _ = writeln!(out, "    healthcheck:");
        let _ = writeln!(
            out,
            "      test: {}",
            quoted_list(["CMD", "mensura", "health", health_addr.as_str()])
        );
        let _ = writeln!(out, "      interval: 10s");
        let _ = writeln!(out, "      timeout: 5s");
        let _ = writeln!(out, "      retries: 3");
        let _ = writeln!(out, "      start_period: 30s");
    }
    let _ = writeln!(out, "\nvolumes:\n  data: {{}}");
    out
}

/// `up.sh`: bring the project up and wait until every instance is ready.
pub fn up_script() -> String {
    "#!/bin/sh\n\
     # Generated by `mensura deploy`.  Brings the deployment up and waits\n\
     # until every instance reports ready; services whose files changed\n\
     # are recreated.  Extra arguments go to `docker compose up`.\n\
     set -eu\n\
     cd \"$(dirname \"$0\")\"\n\
     exec docker compose up --detach --wait \"$@\"\n"
        .to_string()
}

/// `down.sh`: stop and remove the services.  The data volume survives
/// unless `--volumes` is passed.
pub fn down_script() -> String {
    "#!/bin/sh\n\
     # Generated by `mensura deploy`.  Stops and removes the services; the\n\
     # data volume survives unless `--volumes` is passed.\n\
     set -eu\n\
     cd \"$(dirname \"$0\")\"\n\
     exec docker compose down \"$@\"\n"
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting_escapes_for_yaml_and_toml() {
        assert_eq!(quote("a\"b\\c"), r#""a\"b\\c""#);
        let parsed: toml::Value = toml::from_str(&format!("x = {}", quote("a\"b\\c\n"))).unwrap();
        assert_eq!(parsed["x"].as_str(), Some("a\"b\\c\n"));
    }
}
